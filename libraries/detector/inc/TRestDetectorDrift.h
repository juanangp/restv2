#ifndef TRESTDETECTORDRIFT_H
#define TRESTDETECTORDRIFT_H

#include <memory>
#include <string>
#include <vector>

#include "Math/Vector3D.h"
#include "TRestMetadata.h"

class TRandom;
class TRestDetectorTransport;

/// \class TRestDetectorDrift
/// \brief Properties of the medium where the ionization electrons drift (gas, liquid...) at its operating
/// point: electric field, pressure and temperature, given in the YAML since they depend on the
/// experimental conditions.
///
/// The transport parameters (driftVelocity, longDiff, transDiff, attachment) are given in the YAML or
/// interpolated at electricField and pressure from a table of the medium file (TRestDetectorTransport,
/// e.g. ArIso.root generated by restGarfield; Garfield++ is not needed):
/// - mediumFile: path of the medium file (a leading ~ is $HOME);
/// - medium: name of the medium in the file (by default the file name, e.g. ArIso for ArIso.root);
/// - table: key of the table (e.g. "1bar_293.15K_E10-1000Vcm"). If empty, the table at pressure and
///   temperature whose field range contains electricField (the narrowest if several), or else, for gases,
///   the closest pressure containing it scaled with E/p (with a warning).
///
/// The values of the table replace those of the YAML and the values used, with the file and table, are
/// written back, so a processed run keeps them. If the file is not found but the YAML has a driftVelocity
/// (e.g. the metadata of a processed run) the YAML values are used with a warning. The whole table is
/// kept: the getters with a field give the parameters at any field (e.g. for non-uniform fields) and for
/// each carrier of the table (electron, hole, ion); without table they give the YAML values, valid only
/// for electrons at electricField.
///
/// Parameters:
/// - electricField: drift field (e.g. 100 V/cm).
/// - pressure (1 bar), temperature (293.15, in K; only checked against the table).
/// - wValue: mean energy to create an ionization electron (e.g. 26.2 eV). Mandatory.
/// - fanoFactor (0).
/// - driftVelocity (0, e.g. 11.5 mm/us): only needed by the processes that convert time and distance.
/// - longDiff, transDiff (0): longitudinal and transversal diffusion coefficients in sqrt(cm), as Garfield
///   and legacy (sigma = D * sqrt(drift distance)).
/// - attachment (0): attachment coefficient in 1/cm (survival probability exp(-attachment * distance)).
/// - mediumFile, medium, table ("").
///
/// Example:
///
///    driftMedium:
///      class: "TRestDetectorDrift"
///      name: "ArIso"
///      mediumFile: "~/.rest/media/ArIso.root"
///      electricField: 100 V/cm
///      wValue: 26.2 eV
///      fanoFactor: 0.2
class TRestDetectorDrift : public TRestMetadata {
   private:
    std::shared_ptr<const TRestDetectorTransport> fTransport;  //!

    /// \brief Key of the table for pressure, temperature and electricField (see class description)
    std::string SelectTable(const YAML::Node& tables) const;
    void LoadTransportTable();
    void CheckParameters() const;

   public:
    TRestWithUnits fElectricField = 0;
    TRestWithUnits fPressure = 1;
    double fTemperature = 293.15;
    TRestWithUnits fWValue = 0;
    double fFanoFactor = 0;
    TRestWithUnits fDriftVelocity = 0;
    double fLongitudinalDiffusion = 0;
    double fTransversalDiffusion = 0;
    double fAttachment = 0;
    std::string fMedium = "";
    std::string fMediumFile = "";
    std::string fTable = "";

    TRestDetectorDrift();
    TRestDetectorDrift(const std::string& instanceName, const YAML::Node& node);
    TRestDetectorDrift(const std::string& fileName, const std::string& sectionName);

    std::string GetClassName() const override { return "TRestDetectorDrift"; }
    void LoadConfig() override;
    void Initialize() override {}

    inline double GetElectricField() const { return fElectricField; }
    inline double GetPressure() const { return fPressure; }
    inline double GetTemperature() const { return fTemperature; }
    inline double GetWValue() const { return fWValue; }
    inline double GetFanoFactor() const { return fFanoFactor; }
    inline double GetDriftVelocity() const { return fDriftVelocity; }
    inline double GetLongitudinalDiffusion() const { return fLongitudinalDiffusion; }
    inline double GetTransversalDiffusion() const { return fTransversalDiffusion; }
    inline double GetAttachment() const { return fAttachment; }

    /// \brief Whether the transport parameters come from a table of the medium file
    inline bool HasTransportTable() const { return fTransport != nullptr; }
    /// \brief Transport table, nullptr if the parameters come from the YAML
    inline const TRestDetectorTransport* GetTransportTable() const { return fTransport.get(); }

    /// Parameters of a carrier at a field (V/mm) and the pressure of the medium. Without table, the YAML
    /// values (only electrons, Townsend 0). Throw if the carrier is not available
    double GetDriftVelocity(double field, const std::string& carrier = "electron") const;
    double GetLongitudinalDiffusion(double field, const std::string& carrier = "electron") const;
    double GetTransversalDiffusion(double field, const std::string& carrier = "electron") const;
    double GetTownsend(double field, const std::string& carrier = "electron") const;
    double GetAttachment(double field, const std::string& carrier = "electron") const;

    /// \brief Drifts one electron created at position, at distance (> 0) from the readout along normal
    /// (unit vector pointing to the cathode): gaussian diffusion (sigma = D * sqrt(distance)) and
    /// attachment.
    /// \return false if the electron is attached. Otherwise position is the diffused position.
    bool DiffuseElectron(ROOT::Math::XYZVector& position, const ROOT::Math::XYZVector& normal,
                         double distance, TRandom& random) const;
};

#endif
