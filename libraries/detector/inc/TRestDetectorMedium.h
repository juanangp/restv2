/// \class TRestDetectorChargeResponse
/// \brief Charge response of a medium: ionisation (W-value, Fano factor), transport of the charge carriers
/// versus the field and avalanche gain, from the tables of the medium file (TRestDetectorTransportTable,
/// TRestDetectorGainTable, generated by restGarfield) at the pressure and temperature of the medium, or
/// fixed transport parameters without tables.
///
/// It is the `charge` key of a TRestDetectorMedium (no class key), which creates it and gives it its file
/// and conditions; the processes ask the medium for it (TRestDetectorMedium::GetChargeResponse) and it for
/// the parameters at the drift field (e.g. charge.GetDriftVelocity()) or at a given field.
///
/// Parameters:
/// - wValue: mean energy to create an ionisation electron (e.g. 26.2 eV); fanoFactor (0).
/// - driftField: the drift field of the detector (e.g. 140 V/cm), where the transport tables are evaluated
///   for the drift processes; needed with transport tables. Two drift regions are two media.
/// - driftVelocity, longDiff, transDiff (sqrt(cm)), attachment (1/cm): fixed electron transport, used
///   when there are no transport tables (e.g. no mediumFile), for any field.
/// - transportTable: key of the transport table to use (all the tables at the conditions if empty).
/// - loadedTables: written with the keys of the tables loaded (not an input).
///
/// Transport tables: all those at the pressure and temperature of the medium or else, for gases, those at
/// the closest pressure scaled with E/p. For a field, the narrowest table whose range contains it; out of
/// all of them, the closest one (constant out of its range), with a warning the first time. Amplification
/// tables: those at the pressure and temperature (the gain does not scale with the pressure), chosen by gap
/// and key (GetGainTable).
///
///    medium:
///      class: "TRestDetectorMedium"
///      name: "ArIso"
///      mediumFile: "ArIso.root"
///      pressure: 1 bar
///      charge:
///        wValue: 26.2 eV
///        fanoFactor: 0.2
///        driftField: 140 V/cm
class TRestDetectorChargeResponse : public TRestMetadata {
   private:
    std::vector<std::shared_ptr<const TRestDetectorTransportTable>> fTransportTables;  //!
    std::vector<std::shared_ptr<const TRestDetectorGainTable>> fGainTables;            //!
    /// Warning of a field out of the transport tables already given (shared by the copies)
    std::shared_ptr<std::atomic<bool>> fRangeWarned = std::make_shared<std::atomic<bool>>(false);  //!
    /// Name and conditions of the medium
    std::string fMediumName = "";  //!
    double fPressure = 1;          //!
    double fTemperature = 293.15;  //!

    void LoadTables(TFile* file);
    void CheckCarrier(const std::string& carrier) const;
    /// Drift field (V/mm); throws if there are transport tables and no driftField
    double GetDriftFieldForTables() const;

   public:
    TRestWithUnits fWValue = 0;
    double fFanoFactor = 0;
    TRestWithUnits fDriftField = 0;
    TRestWithUnits fDriftVelocity = 0;
    double fLongitudinalDiffusion = 0;
    double fTransversalDiffusion = 0;
    double fAttachment = 0;
    std::string fTransportTable = "";
    std::vector<std::string> fLoadedTables;

    TRestDetectorChargeResponse();
    TRestDetectorChargeResponse(const std::string& instanceName, const YAML::Node& node);
    ~TRestDetectorChargeResponse() override;

    std::string GetClassName() const override { return "TRestDetectorChargeResponse"; }
    void LoadConfig() override;
    void Initialize() override {}

    /// \brief Sets the medium (name, pressure, temperature) and loads its tables from its medium file,
    /// opened by the medium (nullptr: no tables)
    void SetMedium(const TRestDetectorMedium& medium, TFile* file);

    inline double GetWValue() const { return fWValue; }
    inline double GetFanoFactor() const { return fFanoFactor; }
    /// \brief Drift field in V/mm (0 if not given)
    inline double GetDriftField() const { return fDriftField; }

    /// \brief Whether there are transport tables (otherwise the fixed parameters are used)
    inline bool HasTransportTables() const { return !fTransportTables.empty(); }
    /// \brief Transport table for a field (V/mm), nullptr without tables (see class description)
    const TRestDetectorTransportTable* GetTransportTable(double field) const;

    /// Parameters of a carrier at a field (V/mm) and the pressure of the medium. Without tables, the fixed
    /// ones (only electrons, Townsend 0). Throw if the carrier is not available
    double GetDriftVelocity(double field, const std::string& carrier = "electron") const;
    double GetLongitudinalDiffusion(double field, const std::string& carrier = "electron") const;
    double GetTransversalDiffusion(double field, const std::string& carrier = "electron") const;
    double GetTownsend(double field, const std::string& carrier = "electron") const;
    double GetAttachment(double field, const std::string& carrier = "electron") const;
    /// Electron parameters at the drift field (driftField; without transport tables, the fixed ones).
    /// Throw if there are transport tables and no driftField
    double GetDriftVelocity() const;
    double GetLongitudinalDiffusion() const;
    double GetTransversalDiffusion() const;
    double GetAttachment() const;

    /// \brief Gain table of a gap (mm) at the pressure and temperature of the medium, with the key if not
    /// empty. Throws if there is none, or several and no key.
    const TRestDetectorGainTable& GetGainTable(double gap, const std::string& key = "") const;

    /// \brief Drifts one electron created at position, at distance (> 0, mm) from the readout along normal
    /// (unit vector pointing to the cathode): gaussian diffusion (sigma = D * sqrt(distance), D in
    /// sqrt(cm)) and attachment (1/cm), the coefficients at the field (GetLongitudinalDiffusion...).
    /// \return false if the electron is attached. Otherwise position is the diffused position.
    static bool DiffuseElectron(ROOT::Math::XYZVector& position, const ROOT::Math::XYZVector& normal,
                                double distance, double longDiff, double transDiff, double attachment,
                                TRandom& random);
};

/// \class TRestDetectorLightResponse
/// \brief Light response of a scintillating medium: the propagation of the light to the photocathode (used
/// by TRestDetectorLightAttenuationProcess). It is the `light` key of a TRestDetectorMedium (no class key).
/// The light yield, decay time, quenching or quantum efficiency will be other parameters when the light
/// is parametrised.
///
/// Parameters:
/// - attenuationLength: the deposited energy reaching the readout is E exp(-d / attenuationLength), with d
///   the distance to the readout of the channel (TRestDetectorReadout::GetDistanceToReadout).
/// - effectiveLightSpeed: the signal is delayed by d / effectiveLightSpeed (effective speed along the
///   scintillator, with its reflections).
///
///      light:
///        attenuationLength: 3 m
///        effectiveLightSpeed: 150 mm/ns
class TRestDetectorLightResponse : public TRestMetadata {
   public:
    TRestWithUnits fAttenuationLength = 0;    // mm
    TRestWithUnits fEffectiveLightSpeed = 0;  // mm/us

    TRestDetectorLightResponse();
    TRestDetectorLightResponse(const std::string& instanceName, const YAML::Node& node);

    std::string GetClassName() const override { return "TRestDetectorLightResponse"; }
    void LoadConfig() override;
    void Initialize() override {}

    inline double GetAttenuationLength() const { return fAttenuationLength; }
    inline double GetEffectiveLightSpeed() const { return fEffectiveLightSpeed; }
};

/// \class TRestDetectorMedium
/// \brief A material (gas, liquid or solid) at its conditions, with its medium file (the tables generated
/// by restGarfield, read without Garfield++) and its responses. It describes the material, not the detector
/// technology: what is measured in it is given by the readout and the responses.
///
/// The same section is used by restGarfield (the `medium` of a TRestDetectorTransportManager: it writes
/// its tables to mediumFile, components needed) and by the processes (a metadata of the
/// TRestManager, found by name with their `medium` field). It is self-contained: LoadConfig reads the
/// medium file, if it exists, and gives it with the conditions to its responses.
///
/// Parameters:
/// - name: the name of the medium in its file.
/// - state: gas, liquid or solid.
/// - components: names and molar fractions in percent (for gases, volume fractions or partial
///   pressures), e.g. {Ar: 99, iC4H10: 1} or {Si: 100}. Read from the medium file if not given; if given,
///   they must agree with it.
/// - mediumFile: path of the medium file (a leading ~ is $HOME). restGarfield writes to it (by default
///   `<name>.root`).
/// - pressure (gases only, 1 bar), temperature (293.15 K): the conditions of the detector (and the default
///   ones of the tables of restGarfield). A pressure other than 1 bar for a liquid or a solid is an error
///   (1 bar is accepted, it is written to the metadata for any state).
/// - Responses, each one a key without class: `charge` (TRestDetectorChargeResponse: ionisation, transport
///   and gain) and `light` (TRestDetectorLightResponse: propagation of the scintillation light).
///
///    medium:
///      class: "TRestDetectorMedium"
///      name: "ArIso"
///      mediumFile: "~/.rest/media/ArIso.root"
///      pressure: 1.4 bar
///      charge:
///        wValue: 26.2 eV
///        fanoFactor: 0.2
///        driftField: 140 V/cm
class TRestDetectorMedium : public TRestMetadata {
   private:
    std::shared_ptr<TRestDetectorChargeResponse> fCharge;  //!
    std::shared_ptr<TRestDetectorLightResponse> fLight;    //!

   public:
    inline static const std::vector<std::string> kStates = {"gas", "liquid", "solid"};
    std::string fState = "gas";
    std::map<std::string, double> fComponents;
    std::string fMediumFile = "";
    TRestWithUnits fPressure = 1;
    double fTemperature = 293.15;
    /// Configuration of the charge response (`charge` key)
    YAML::Node fChargeNode;
    /// Configuration of the light response (`light` key)
    YAML::Node fLightNode;

    TRestDetectorMedium();
    TRestDetectorMedium(const std::string& instanceName, const YAML::Node& node);
    TRestDetectorMedium(const std::string& fileName, const std::string& sectionName);
    ~TRestDetectorMedium() override;

    std::string GetClassName() const override { return "TRestDetectorMedium"; }
    void LoadConfig() override;
    void Initialize() override {}

    inline bool IsGas() const { return fState == "gas"; }
    inline double GetPressure() const { return fPressure; }
    inline double GetTemperature() const { return fTemperature; }

    /// \brief Charge response, nullptr if the medium has no `charge`
    inline const TRestDetectorChargeResponse* GetChargeResponse() const { return fCharge.get(); }
    /// \brief Charge response; throws if the medium has no `charge` (user is for the message)
    const TRestDetectorChargeResponse& GetChargeResponse(const std::string& user) const;

    /// \brief Light response, nullptr if the medium has no `light`
    inline const TRestDetectorLightResponse* GetLightResponse() const { return fLight.get(); }
    /// \brief Light response; throws if the medium has no `light` (user is for the message)
    const TRestDetectorLightResponse& GetLightResponse(const std::string& user) const;

    /// \brief YAML of the medium stored in its file (name, state, components)
    YAML::Node GetDefinition() const;
    /// \brief Path of the medium file: mediumFile (~ expanded) or `<name>.root`
    std::filesystem::path GetMediumFile() const;
    /// \brief Metadata of the medium name in a medium file to update: the stored one, or definition if the
    /// file has none. Throws if the components of definition and of the file differ.
    static YAML::Node GetFileMetadata(TFile* file, const std::string& name, const YAML::Node& definition);
};

