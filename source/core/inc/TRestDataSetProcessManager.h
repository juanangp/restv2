#ifndef TRESTDATASETPROCESSMANAGER_H
#define TRESTDATASETPROCESSMANAGER_H

#include <map>
#include <memory>
#include <string>
#include <vector>

#include "TRestDataSetProcess.h"
#include "TRestMetadata.h"

class TRestDataSet;
class TRestManager;

/// \class TRestDataSetProcessManager
/// \brief Pipeline of dataset processes (TRestDataSetProcess): opens a dataset, each process obtains its
/// parameters and adds its columns, in order, and the processed dataset is written once. See the class
/// documentation in TRestDataSetProcessManager.cxx.
class TRestDataSetProcessManager : public TRestMetadata {
   private:
    std::vector<std::unique_ptr<TRestDataSetProcess>> fProcesses;
    TRestManager* fManager = nullptr;

    /// \brief Processes a dataset and writes the output (Run); `inputFile` is its file, empty for a dataset
    /// generated in memory (then there are no processes of an input to keep)
    void Process(TRestDataSet& dataSet, const std::string& inputFile);

   public:
    /// Dataset processed (a dataset file already generated); empty for the dataset generated by the
    /// manager (Run(TRestDataSet&))
    std::string fInputFileName = "";
    /// Dataset written; [key] from the tags of inputFormat or the runs of the input (ResolveOutputFileName)
    std::string fOutputFileName = "";
    /// Pattern of the name of the input dataset with [tag] (e.g. "Dataset_[runTag].root"), whose values are
    /// the [tag] of outputFileName
    std::string fInputFormat = "";

    TRestDataSetProcessManager();
    TRestDataSetProcessManager(const std::string& instanceName, const YAML::Node& node);

    std::string GetClassName() const override { return "TRestDataSetProcessManager"; }
    void LoadConfig() override;
    void Initialize() override {}

    void SetManager(TRestManager* manager) { fManager = manager; }

    const std::vector<std::unique_ptr<TRestDataSetProcess>>& GetProcesses() const { return fProcesses; }

    /// \brief Processes the input dataset and writes the output: the dataset (all its columns and the new
    /// ones, its runs and metadata), this pipeline and each process with its results (RESTMetadataStore),
    /// the TRestCut used and the objects of each process (its folder); the folders of the processes of the
    /// input dataset are kept.
    void Run();
    /// \brief Processes a dataset generated in memory (the TRestDataSet of the manager, not written): only
    /// the processed dataset is written, with the configuration of the generation
    void Run(TRestDataSet& dataSet);

    /// \brief The tags of inputFormat in the name of the input dataset (tag -> value); throws if the name
    /// does not match it
    std::map<std::string, std::string> ParseInputFormat() const;
    /// \brief outputFileName with each [key] replaced: the tag of inputFormat, otherwise a key of the runs of
    /// the dataset (TRestDataSet::ResolveFilePattern: [runRange], [runTag]...)
    std::string ResolveOutputFileName(const TRestDataSet& dataSet) const;
};

#endif
