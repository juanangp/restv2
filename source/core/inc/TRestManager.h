#ifndef TRESTMANAGER_H
#define TRESTMANAGER_H

#include <atomic>
#include <memory>
#include <stdexcept>
#include <string>
#include <vector>

#include "TRestMetadata.h"

class TRestRun;

class TRestEventProcessManager;
class TRestDataSetProcessManager;
class TRestDataSet;

/// \class TRestManager
/// \brief Top-level orchestrator that loads configured metadata classes.
///
/// `TRestManager` parses configuration and instantiates metadata objects.
/// Event pipeline execution is delegated to `TRestEventProcessManager`; after it, RunPlots draws the
/// TRestAnalysisPlot of the manager. The TRestRun is the input of the pipeline; a manager with only plots
/// has no TRestRun: each plot has its own input (inputFileName: a run file, a dataset or a pattern). A
/// TRestDataSetProcessManager (dataset pipeline, instead of TRestRun and TRestEventProcessManager) processes
/// a dataset; a TRestDataSet section generates a dataset (with the TRestCut of the manager), processed in
/// memory by the dataset pipeline if there is one (then written only if it has an outputFileName). The plots
/// without inputFileName draw the last output.
class TRestManager : public TRestMetadata {
   private:
    std::vector<std::unique_ptr<TRestMetadata>> fMetaObjects;
    TRestEventProcessManager* fProcessManager = nullptr;
    TRestDataSetProcessManager* fDataSetProcessManager = nullptr;
    /// Dataset generated by the manager (its TRestDataSet section), input of the dataset pipeline if any
    TRestDataSet* fDataSet = nullptr;
    static std::atomic<bool> fStopRequested;

   public:
    TRestManager(const std::string& instanceName, const YAML::Node& node);
    TRestManager(const std::string& fileName, const std::string& sectionName);
    ~TRestManager() override = default;

    std::string GetClassName() const override { return "TRestManager"; }

    void Run();

    /// \brief Draws every TRestAnalysisPlot of the manager, in declaration order, with its inputFileName (a
    /// run file, a dataset or a pattern, e.g. R*_ANA.root) or, if it has none, the output file of the
    /// pipeline (closed first, call after SaveMetadata). Each plot writes in its own outputFileName.
    void RunPlots();

    void LoadConfig() override;
    void Initialize() override {}
    void SaveMetadata();

    TRestMetadata* GetMetadataClass(const std::string& className) const {
        for (const auto& meta : fMetaObjects) {
            if (meta && meta->GetClassName() == className) return meta.get();
        }
        return nullptr;
    }

    /// \brief Metadata objects of class T or derived from it (e.g. all the drift media), in declaration
    /// order.
    template <class T>
    std::vector<T*> GetMetadataOfType() const {
        std::vector<T*> result;
        for (const auto& meta : fMetaObjects) {
            if (auto* object = dynamic_cast<T*>(meta.get())) result.push_back(object);
        }
        return result;
    }

    /// \brief Metadata of class T with that name, or the only one if name is empty. nullptr if name is empty
    /// and there is none; throws if name is empty and there are several, or if name is not found. user
    /// (e.g. the process) and field (its field with the name) are for the messages.
    template <class T>
    T* FindMetadata(const std::string& name, const std::string& user, const std::string& field) const {
        const auto objects = GetMetadataOfType<T>();
        if (name.empty()) {
            if (objects.size() > 1) {
                throw std::runtime_error(user + ": several " + objects.front()->GetClassName() + ", set '" +
                                         field + "'");
            }
            return objects.empty() ? nullptr : objects.front();
        }
        for (auto* object : objects) {
            if (object->GetName() == name) return object;
        }
        throw std::runtime_error(user + ": " + field + " '" + name + "' not found");
    }

    static void RequestStop() { fStopRequested.store(true, std::memory_order_relaxed); }

    static bool StopRequested() { return fStopRequested.load(std::memory_order_relaxed); }

    static void ResetStopRequest() { fStopRequested.store(false, std::memory_order_relaxed); }

   private:
    void RunMultithreaded(unsigned int nThreads);
};
#endif
